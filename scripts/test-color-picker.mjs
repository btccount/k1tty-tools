import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const modulePath = process.env.K1TTY_QA_MODULES
  ? pathToFileURL(resolve(process.env.K1TTY_QA_MODULES, 'happy-dom/lib/index.js')).href
  : 'happy-dom';
const { Window } = await import(modulePath);
const window = new Window({ url: 'https://k1tty.test/', width: 760, height: 540,
  settings: { disableCSSFileLoading: true, disableJavaScriptFileLoading: true } });
const document = window.document;
const read = path => readFileSync(resolve(root, path), 'utf8');
const frame = () => new Promise(resolve => window.requestAnimationFrame(resolve));
const event = (element, type) => element.dispatchEvent(new window.Event(type, { bubbles: true }));
const errors = [];
window.addEventListener('error', value => errors.push(value.message));
document.write(read('static/index.html').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '').replace(/<link\b[^>]*>/gi, ''));
document.documentElement.lang = 'ru';
const context = vm.createContext(window);
vm.runInContext(read('static/appearance.js'), context);
document.dispatchEvent(new window.Event('DOMContentLoaded'));

try {
  window.K1ttyAppearance.open();
  const dialog = document.getElementById('appearanceDialog');
  const picker = document.getElementById('appearanceColorPicker');
  const plane = document.getElementById('appearancePickerPlane');
  const hue = document.getElementById('appearancePickerHue');
  const hex = document.getElementById('appearancePickerHex');
  const button = document.getElementById('appearanceColor-canvas');
  const getColor = () => window.K1ttyAppearance.getSettings().customColors.canvas;
  dialog.getBoundingClientRect = () => ({ left: 20, top: 20, right: 640, bottom: 496, width: 620, height: 476 });
  button.getBoundingClientRect = () => ({ left: 600, top: 450, right: 632, bottom: 482, width: 32, height: 32 });
  picker.getBoundingClientRect = () => ({ left: 0, top: 0, right: 304, bottom: 416, width: 304, height: 416 });
  document.querySelector('.appearance-palette').open = true;
  assert.equal(dialog.querySelectorAll('input[type="color"]').length, 0);
  assert(picker.hidden);
  button.click();
  await frame();
  assert(!picker.hidden);
  assert.equal(picker.closest('dialog'), dialog);
  assert.equal(button.getAttribute('aria-expanded'), 'true');
  assert.equal(document.activeElement, plane);
  assert.equal(document.getElementById('appearancePickerTitle').textContent, 'Фон окна');
  assert.equal(parseFloat(picker.style.left), 304);
  assert(parseFloat(picker.style.top) >= 12);
  assert(parseFloat(picker.style.top) + 416 <= 464);
  assert.equal(picker.style.maxHeight, '452px');
  picker.querySelector('[data-picker-swatch="#ed747e"]').click();
  assert.equal(getColor(), '#ed747e');

  let reads = 0;
  plane.getBoundingClientRect = () => { reads++; return { left: 50, top: 100, right: 250, bottom: 200, width: 200, height: 100 }; };
  hue.value = '0'; event(hue, 'input'); event(hue, 'change');
  plane.dispatchEvent(new window.PointerEvent('pointerdown', { pointerId: 1, button: 0, clientX: 250, clientY: 100, bubbles: true, cancelable: true }));
  plane.dispatchEvent(new window.PointerEvent('pointerdown', { pointerId: 2, button: 0, clientX: 50, clientY: 200, bubbles: true, cancelable: true }));
  for (let i = 0; i < 40; i++) plane.dispatchEvent(new window.PointerEvent('pointermove', { pointerId: 1, clientX: 250, clientY: 100, bubbles: true }));
  plane.dispatchEvent(new window.PointerEvent('pointerup', { pointerId: 1, clientX: 250, clientY: 100, bubbles: true }));
  assert.equal(getColor(), '#ff0000');
  assert.equal(reads, 1, 'A drag reads geometry once and ignores a second pointer');
  assert.equal(plane.getAttribute('aria-valuenow'), '100');
  assert.match(plane.getAttribute('aria-valuetext'), /100%/);
  hue.value = '120'; event(hue, 'input'); event(hue, 'change');
  assert.equal(getColor(), '#00ff00');
  const key = new window.KeyboardEvent('keydown', { key: 'ArrowLeft', shiftKey: true, bubbles: true, cancelable: true });
  plane.dispatchEvent(key); event(plane, 'keyup');
  assert(key.defaultPrevented);
  assert.equal(getColor(), '#1aff1a');

  const channels = [...picker.querySelectorAll('[data-picker-channel]')];
  for (const [index, value] of [128, 16, 64].entries()) channels[index].value = String(value);
  event(channels[0], 'input'); event(channels[0], 'change');
  assert.equal(getColor(), '#801040');
  assert.equal(hex.value, '#801040');
  channels[0].focus(); channels[0].value = '999'; event(channels[0], 'input');
  assert.equal(channels[0].getAttribute('aria-invalid'), 'true');
  assert.equal(getColor(), '#801040', 'Invalid channel values never reach preferences');
  event(channels[0], 'change');
  assert.equal(channels[0].value, '128');
  assert.equal(channels[0].hasAttribute('aria-invalid'), false);
  hex.focus(); hex.value = 'f00'; event(hex, 'input'); event(hex, 'change');
  assert.equal(getColor(), '#ff0000');
  assert.equal(hex.value, '#ff0000');
  hex.value = '#zzzzzz'; event(hex, 'input');
  assert.equal(hex.getAttribute('aria-invalid'), 'true');
  assert.equal(getColor(), '#ff0000');
  event(hex, 'change');
  assert.equal(hex.value, '#ff0000');
  picker.querySelector('[data-picker-previous]').click();
  assert.equal(getColor(), '#141415');
  const escape = new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true });
  plane.dispatchEvent(escape);
  assert(escape.defaultPrevented);
  assert(picker.hidden && dialog.open);
  assert.equal(document.activeElement, button);
  assert.equal(button.getAttribute('aria-expanded'), 'false');

  button.click();
  const cancel = new window.Event('cancel', { cancelable: true });
  dialog.dispatchEvent(cancel);
  assert(cancel.defaultPrevented && picker.hidden && dialog.open);
  button.click();
  hex.value = '#451122'; event(hex, 'input');
  document.querySelector('.appearance-content').dispatchEvent(new window.Event('scroll'));
  assert(picker.hidden);
  assert.equal(getColor(), '#451122');
  assert.equal(JSON.parse(window.localStorage.getItem('k1tty_appearance_v1')).customColors.canvas, '#451122');
  button.click();
  document.querySelector('.appearance-head').dispatchEvent(new window.PointerEvent('pointerdown', { bubbles: true, pointerId: 4 }));
  assert(picker.hidden && dialog.open);
  button.click();
  window.dispatchEvent(new window.Event('resize'));
  assert(picker.hidden && dialog.open);
  button.click();
  picker.querySelector('[data-picker-close]').click();
  assert(picker.hidden && dialog.open);
  button.click();
  window.K1ttyAppearance.close();
  assert(!dialog.open && picker.hidden);
  assert.deepEqual(errors, []);
  console.log('PASS: custom picker HSV/pointer/keyboard, HEX/RGB validation, swatches, previous color, bounds, queued persistence, Escape/cancel/outside/scroll/resize and focus restoration. DOM with modeled geometry; no browser rendering claim.');
} finally { await window.happyDOM.close(); }
